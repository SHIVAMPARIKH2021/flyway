DO $$
BEGIN
    -- Check if 'id' in analytics.fund_benchmark_association is currently UUID
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'analytics'
          AND table_name = 'fund_benchmark_association'
          AND column_name = 'id'
          AND data_type = 'uuid'
    ) THEN

        -- 1. Drop existing primary key constraint
        ALTER TABLE analytics.fund_benchmark_association
            DROP CONSTRAINT IF EXISTS fund_benchmark_association_pkey;

        -- 2. Drop the old UUID column completely
        ALTER TABLE analytics.fund_benchmark_association
            DROP COLUMN id;

        -- 3. Add fresh INT id column with auto-generating IDENTITY primary key
        ALTER TABLE analytics.fund_benchmark_association
            ADD COLUMN id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;

    END IF;

    -- 4. Add created_by / updated_by tracking columns if missing
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'analytics'
          AND table_name = 'fund_benchmark_association'
          AND column_name = 'created_by'
    ) THEN
        ALTER TABLE analytics.fund_benchmark_association
            ADD COLUMN created_by VARCHAR(50),
            ADD COLUMN updated_by VARCHAR(50);
    END IF;

END $$;

-- 5. Composite unique index on (series_id, benchmark_id)
CREATE UNIQUE INDEX IF NOT EXISTS idx_uq_fba_series_benchmark
    ON analytics.fund_benchmark_association (series_id, benchmark_id);

-- 6. Lookup indexes
CREATE INDEX IF NOT EXISTS idx_fba_accession_number
    ON analytics.fund_benchmark_association (accession_number);

CREATE INDEX IF NOT EXISTS idx_fba_benchmark_id
    ON analytics.fund_benchmark_association (benchmark_id);

CREATE INDEX IF NOT EXISTS idx_fba_series_id
    ON analytics.fund_benchmark_association (series_id);