DO $$
BEGIN
    -- Only run migration if the table exists
    IF EXISTS (
        SELECT 1
        FROM information_schema.tables
        WHERE table_schema = 'analytics'
          AND table_name = 'fund_benchmark_association'
    ) THEN

        -- 1. Create a replacement table with 'id' as the 1st column
        CREATE TABLE analytics.fund_benchmark_association_new (
            id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            series_id         VARCHAR(20) NOT NULL,
            benchmark_id      INT NOT NULL,
            benchmark_name    TEXT,
            is_primary        BOOLEAN DEFAULT FALSE,
            accession_number  VARCHAR(25),
            created_at        TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
            created_by        VARCHAR(50),
            updated_at        TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
            updated_by        VARCHAR(50),

            CONSTRAINT fk_fba_fund_master
                FOREIGN KEY (series_id)
                REFERENCES analytics.fund_master(series_id)
                ON DELETE CASCADE,

            CONSTRAINT fk_fba_benchmark_master
                FOREIGN KEY (benchmark_id)
                REFERENCES analytics.benchmark_master(benchmark_id)
                ON DELETE CASCADE
        );

        -- 2. Copy existing data over (id will auto-generate sequential integers)
        INSERT INTO analytics.fund_benchmark_association_new (
            series_id,
            benchmark_id,
            benchmark_name,
            is_primary,
            accession_number,
            created_at,
            updated_at
        )
        SELECT
            series_id,
            benchmark_id::int,
            benchmark_name,
            is_primary,
            accession_number,
            created_at,
            updated_at
        FROM analytics.fund_benchmark_association;

        -- 3. Drop the old table and rename the new table
        DROP TABLE analytics.fund_benchmark_association CASCADE;
        ALTER TABLE analytics.fund_benchmark_association_new
            RENAME TO fund_benchmark_association;

        -- 4. Re-establish table constraints with standard naming
        ALTER TABLE analytics.fund_benchmark_association
            RENAME CONSTRAINT fund_benchmark_association_new_pkey TO fund_benchmark_association_pkey;

    END IF;
END $$;

-- 5. Recreate Indexes
CREATE UNIQUE INDEX IF NOT EXISTS idx_uq_fba_series_benchmark
    ON analytics.fund_benchmark_association (series_id, benchmark_id);

CREATE INDEX IF NOT EXISTS idx_fba_series_id
    ON analytics.fund_benchmark_association (series_id);

CREATE INDEX IF NOT EXISTS idx_fba_benchmark_id
    ON analytics.fund_benchmark_association (benchmark_id);

CREATE INDEX IF NOT EXISTS idx_fba_accession_number
    ON analytics.fund_benchmark_association (accession_number);