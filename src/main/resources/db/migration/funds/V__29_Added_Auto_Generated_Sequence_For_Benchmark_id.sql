DO $$
BEGIN
    -- Check if benchmark_id already has an identity sequence
    IF NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'analytics'
          AND table_name = 'benchmark_master'
          AND column_name = 'benchmark_id'
          AND is_identity = 'YES'
    ) THEN
        -- Attach identity generator
        ALTER TABLE analytics.benchmark_master
            ALTER COLUMN benchmark_id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;

    -- Restart/align sequence to avoid key collisions with existing rows
    EXECUTE format(
        'ALTER TABLE analytics.benchmark_master ALTER COLUMN benchmark_id RESTART WITH %s',
        COALESCE((SELECT MAX(benchmark_id) FROM analytics.benchmark_master), 0) + 1
    );
END $$;