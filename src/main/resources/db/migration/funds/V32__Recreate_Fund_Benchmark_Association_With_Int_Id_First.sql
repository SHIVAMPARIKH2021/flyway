-- 1. Create the new table with id as the 1st column (INT GENERATED AS IDENTITY)
CREATE TABLE analytics.fund_benchmark_association_new (
    id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id         VARCHAR(20) NOT NULL,
    benchmark_id      INT NOT NULL,
    benchmark_name    TEXT,
    is_primary        BOOLEAN DEFAULT FALSE,
    accession_number  VARCHAR(25),
    created_at        TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    created_by        VARCHAR(50),
    updated_at        TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_by        VARCHAR(50),

    CONSTRAINT fk_fba_fund_master
        FOREIGN KEY (series_id)
        REFERENCES analytics.fund_master(series_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_fba_benchmark_master
        FOREIGN KEY (benchmark_id)
        REFERENCES analytics.benchmark_master(benchmark_id)
        ON DELETE CASCADE
);

-- 2. Migrate existing data (safely handling whether id was UUID, INT, or newly generated)
INSERT INTO analytics.fund_benchmark_association_new (
    series_id,
    benchmark_id,
    benchmark_name,
    is_primary,
    accession_number,
    created_at,
    created_by,
    updated_at,
    updated_by
)
SELECT
    series_id,
    benchmark_id::int,
    benchmark_name,
    is_primary,
    accession_number,
    created_at,
    COALESCE(created_by, 'MIGRATION'),
    updated_at,
    COALESCE(updated_by, 'MIGRATION')
FROM analytics.fund_benchmark_association;

-- 3. Reset the identity sequence so future inserts do not collide
SELECT setval(
    pg_get_serial_sequence('analytics.fund_benchmark_association_new', 'id'),
    COALESCE((SELECT MAX(id) FROM analytics.fund_benchmark_association_new), 1),
    true
);

-- 4. Swap the tables atomically
DROP TABLE analytics.fund_benchmark_association CASCADE;

ALTER TABLE analytics.fund_benchmark_association_new
    RENAME TO fund_benchmark_association;

ALTER TABLE analytics.fund_benchmark_association
    RENAME CONSTRAINT fund_benchmark_association_new_pkey TO fund_benchmark_association_pkey;

-- 5. Recreate Indexes on the fresh table
CREATE UNIQUE INDEX idx_uq_fba_series_benchmark
    ON analytics.fund_benchmark_association (series_id, benchmark_id);

CREATE INDEX idx_fba_series_id
    ON analytics.fund_benchmark_association (series_id);

CREATE INDEX idx_fba_benchmark_id
    ON analytics.fund_benchmark_association (benchmark_id);

CREATE INDEX idx_fba_accession_number
    ON analytics.fund_benchmark_association (accession_number);