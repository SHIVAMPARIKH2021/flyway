DO $$
BEGIN
    -- Check if 'id' in analytics.fund_benchmark_association is currently UUID
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'analytics'
          AND table_name = 'fund_benchmark_association'
          AND column_name = 'id'
          AND data_type = 'uuid'
    ) THEN

        -- 1. Drop existing primary key constraint
        ALTER TABLE analytics.fund_benchmark_association
            DROP CONSTRAINT IF EXISTS fund_benchmark_association_pkey;

        -- 2. Drop the UUID default generator
        ALTER TABLE analytics.fund_benchmark_association
            ALTER COLUMN id DROP DEFAULT;

        -- 3. Alter 'id' column type to INT and attach IDENTITY sequence
        -- Note: Existing UUIDs cannot be cast directly to INT, so existing IDs are reset via row_number
        ALTER TABLE analytics.fund_benchmark_association
            ALTER COLUMN id TYPE INT
            USING NULL;

        ALTER TABLE analytics.fund_benchmark_association
            ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

        -- 4. Re-establish Primary Key on 'id'
        ALTER TABLE analytics.fund_benchmark_association
            ADD CONSTRAINT fund_benchmark_association_pkey PRIMARY KEY (id);

    END IF;

    -- 5. Ensure series_id is nullable for Step 2 staging
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'analytics'
          AND table_name = 'fund_benchmark_association'
          AND column_name = 'series_id'
          AND is_nullable = 'NO'
    ) THEN
        ALTER TABLE analytics.fund_benchmark_association
            ALTER COLUMN series_id DROP NOT NULL;
    END IF;

    -- 6. Add created_by / updated_by tracking columns if missing
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'analytics'
          AND table_name = 'fund_benchmark_association'
          AND column_name = 'created_by'
    ) THEN
        ALTER TABLE analytics.fund_benchmark_association
            ADD COLUMN created_by VARCHAR(50),
            ADD COLUMN updated_by VARCHAR(50);
    END IF;

END $$;

-- 7. Replace old composite unique index with staging-friendly partial indexes
DROP INDEX IF EXISTS analytics.idx_uq_fba_series_benchmark;

-- For Step 2: Allows multiple filings to stage (accession_number, benchmark_id) with series_id IS NULL
CREATE UNIQUE INDEX IF NOT EXISTS uq_fund_benchmark_staging
    ON analytics.fund_benchmark_association (accession_number, benchmark_id)
    WHERE series_id IS NULL;

-- For Step 3: Guarantees unique (series_id, benchmark_id) pairs once enriched
CREATE UNIQUE INDEX IF NOT EXISTS uq_fund_benchmark_final
    ON analytics.fund_benchmark_association (accession_number, series_id, benchmark_id)
    WHERE series_id IS NOT NULL;

-- 8. Lookup indexes
CREATE INDEX IF NOT EXISTS idx_fba_accession_number
    ON analytics.fund_benchmark_association (accession_number);

CREATE INDEX IF NOT EXISTS idx_fba_benchmark_id
    ON analytics.fund_benchmark_association (benchmark_id);